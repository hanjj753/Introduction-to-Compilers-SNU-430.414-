#ifndef SUBC_H
#define SUBC_H

#include <stddef.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

/* Name-table classification, not Bison token codes. */
typedef enum { TOKEN_KEYWORD, TOKEN_IDENTIFIER } TokenKind;

typedef struct Symbol {
    TokenKind kind;
    char *name;
    size_t count;
} Symbol;

/* Student-owned hash table. Same interface as Project 1; reuse your completed hash.c.
 * name points to length readable, non-NUL ASCII bytes; length is 1..4096.
 * The input need not be NUL-terminated. Copy exactly length bytes and append NUL.
 * An existing entry keeps its kind and count. A new entry starts at count 0.
 * Return NULL on allocation failure, preserving the existing table and releasing
 * incomplete allocations. enter() does not increment occurrence counts.
 * The table owns the returned Symbol and its name; callers must not free them.
 * The caller may use the pointer until the next enter() or symbols_destroy().
 * No pointer stability across insertions is required (open addressing is allowed).
 */
Symbol *enter(TokenKind kind, const char *name, size_t length);
/* Free all table-owned memory and reset the table to empty. */
void symbols_destroy(void);

/* Supplied in driver.c. No token-count output in Project 2. */
_Noreturn void fail(const char *message);
void reduce(const char *production);
void yyerror(const char *message);

/* Supplied in subc.l. */
void scanner_begin(void);
int get_lineno(void);

/* Generated by Bison and Flex. */
int yyparse(void);
int yylex(void);
int yylex_destroy(void);
char *yyget_text(void);
extern FILE *yyin;

#endif
